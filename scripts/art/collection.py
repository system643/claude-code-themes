from city_themes import CITIES  # noqa: E402

THEMES += CITIES


def build(spec):
    folder = ROOT / spec["id"]
    (folder / "assets").mkdir(parents=True, exist_ok=True)
    # A theme with a photo (photos.py) keeps it; the others get their painted scene.
    photo = photos.wallpaper_entry(spec["id"])
    if photo is None:
        spec["scene"]().save(folder / "assets" / "wallpaper.jpg", quality=90, optimize=True, progressive=True)
    for kind, signal in zip(("start", "success", "error"), synth.STYLES[spec["sound"]]()):
        synth.save(folder / "assets" / f"{kind}.wav", signal, gain=0.5)

    frames, pal, eyes = spec["sprite"]()
    moods = {}
    for mood, (status, quotes) in spec["moods"].items():
        moods[mood] = {"status": status, "quotes": quotes}
    moods["error"]["frames"] = sprites.angry(frames, eyes)
    terminal = dict(spec["terminal"])
    terminal["effects"] = {"backgroundImage": "assets/wallpaper.jpg", "backgroundImageOpacity": 0.85,
                           "backgroundImageStretchMode": "uniformToFill", "shader": spec["shader"]}
    theme = {
        "$schema": "../../../docs/theme.schema.json",
        "id": spec["id"],
        "name": spec["name"],
        "tagline": spec["tagline"],
        "description": spec["description"],
        "universe": spec["universe"],
        "author": "claude-code-themes",
        **({"credit": spec["credit"]} if spec.get("credit") else {}),
        **({"season": spec["season"]} if spec.get("season") else {}),
        "emoji": spec["emoji"],
        "colors": spec["colors"],
        "banner": spec["banner"],
        "pixelArt": {"palette": {**pal, "R": "#FF4040"}, "fps": 4, "frames": frames},
        "quotes": spec["quotes"],
        "spinnerVerbs": spec["spinnerVerbs"],
        "durationLines": spec["durationLines"],
        "status": spec["status"],
        "welcome": spec["welcome"],
        "persona": spec["persona"],
        "moods": moods,
        "sounds": {"start": "assets/start.wav", "success": "assets/success.wav", "error": "assets/error.wav"},
        "wallpapers": [photo or {"name": spec["description"].split(",")[0].rstrip("."), "file": "assets/wallpaper.jpg"}],
        "terminal": terminal,
    }
    (folder / "theme.json").write_text(json.dumps(theme, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("✓", spec["id"])


if __name__ == "__main__":
    wanted = set(sys.argv[1:])
    for spec in THEMES:
        if not wanted or spec["id"] in wanted:
            build(spec)
